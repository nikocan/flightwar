#!/usr/bin/env node
// Validates the production art package against packages/shared/src/art/manifest.ts.
//   npm run art:check             → report (exit 0)
//   npm run art:check -- --strict → exit 1 if any delivered file is invalid or an APPROVED asset is missing/invalid
//   npm run art:check -- --doc    → regenerate docs/ART_DELIVERY_SPEC.md
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { check, loadManifest, root } from './art-lib.mjs';

const { ART_MANIFEST, ART_CATEGORY_LABELS, POWERUPS_WITHOUT_SHEET_ICON } = await loadManifest();
const args = new Set(process.argv.slice(2));

const results = ART_MANIFEST.map((a) => ({ a, r: check(a) }));

if (args.has('--doc')) {
  const lines = [
    '# Sky Force Evolution — Art Delivery Specification',
    '',
    '_Generated by `npm run art:check -- --doc` from `packages/shared/src/art/manifest.ts`. Do not edit by hand._',
    '',
    '**Approved artwork lock:** every asset must match the user-supplied Sky Force Evolution graphics sheet',
    '(colours, silhouettes, proportions, style). Each asset is an independent file with a transparent background',
    '(except the few marked "no"), exported as WebP (preferred) or PNG at the listed size or larger with the same aspect ratio.',
    '',
    '- Put files under `apps/client/public` at the exact path listed.',
    '- Aircraft/enemies: top view, **nose pointing up**, centred, tight crop with ~4% padding. Bosses face the player (nose down).',
    '- Flipbooks: frames in a row-major grid, equal cell sizes, no gaps.',
    '- No text, buttons or HUD baked into art (except the logo).',
    '- Then run `npm run art:check`. Files are only used in game after visual verification and `status: \'approved\'`.',
    '',
    `Power-ups without a sheet icon (need an art decision): ${POWERUPS_WITHOUT_SHEET_ICON.join(', ')}. The "magnet" icon has no gameplay effect yet.`,
    '',
  ];
  for (const [cat, label] of Object.entries(ART_CATEGORY_LABELS)) {
    const rows = results.filter((x) => x.a.category === cat);
    lines.push(`## ${label} (${rows.length})`, '', '| ID | File | Size (px) | Transparent | Frames | Must match (sheet) | Status |', '|---|---|---|---|---|---|---|');
    for (const { a, r } of rows) {
      const frames = a.frames ? `${a.frames.count} (${a.frames.columns} cols, ${a.frames.fps || '—'} fps)` : '—';
      const st = a.status === 'approved' ? '✅ approved' : r.state === 'valid' ? '🟡 delivered, awaiting review' : r.state === 'invalid' ? '🔴 invalid' : '⏳ awaiting art';
      lines.push(`| \`${a.id}\` | \`public${a.path}\` | ${a.sourceWidth}×${a.sourceHeight} | ${a.alpha ? 'yes' : 'no'} | ${frames} | ${a.reference}${a.notes ? ` — _${a.notes}_` : ''} | ${st} |`);
    }
    lines.push('');
  }
  writeFileSync(resolve(root, 'docs/ART_DELIVERY_SPEC.md'), lines.join('\n'));
  console.log('Wrote docs/ART_DELIVERY_SPEC.md');
}

const count = (s) => results.filter((x) => x.r.state === s).length;
console.log(`\nSky Force Evolution art package — ${ART_MANIFEST.length} assets`);
for (const [cat, label] of Object.entries(ART_CATEGORY_LABELS)) {
  const rows = results.filter((x) => x.a.category === cat);
  const ok = rows.filter((x) => x.r.state === 'valid').length;
  const appr = rows.filter((x) => x.a.status === 'approved').length;
  console.log(`  ${label.padEnd(36)} ${String(ok).padStart(3)}/${rows.length} delivered & valid, ${appr} approved`);
}
console.log(`\n  valid: ${count('valid')}   invalid: ${count('invalid')}   missing: ${count('missing')}`);
for (const { a, r } of results.filter((x) => x.r.state === 'invalid')) console.log(`  ✗ ${a.id}: ${r.problems.join('; ')}`);
const brokenApprovals = results.filter((x) => x.a.status === 'approved' && x.r.state !== 'valid');
for (const { a, r } of brokenApprovals) console.log(`  ✗ APPROVED but ${r.state}: ${a.id}`);
console.log(`  approved: ${results.filter((x) => x.a.status === 'approved').length}`);
if (args.has('--strict') && (count('invalid') > 0 || brokenApprovals.length > 0)) process.exit(1);
